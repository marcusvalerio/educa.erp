await u.page.getByLabel(/^Confirme a senha/).fill(OWNER_PASS);
await u.page.getByRole("button", { name: /Criar senha/ }).click();
await u.page.waitForTimeout(4000);
console.log("depois da senha:", pathOf(u.page));
